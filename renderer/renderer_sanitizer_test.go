package renderer_test

import (
	"context"
	"strings"
	"testing"

	"github.com/resumeee-app/resumeee-core"
	"github.com/resumeee-app/resumeee-core/renderer"
)

func TestRender_UnobfuscatedAuthenticContactDetails(t *testing.T) {
	tmpl := &core.TemplateSet{
		ID:           "test-tmpl",
		Name:         "Test Template",
		HTMLTemplate: `<h1>{{.FullName}}</h1><p>{{.Email}} | {{.Phone}} | {{.Website}}</p><p>{{.Summary}}</p>{{range .Experiences}}<p>{{.DutiesSummary}}</p>{{range .Bullets}}<li>{{.Text}}</li>{{end}}{{end}}`,
		MarkdownTemplate: `# {{.FullName}}
{{.Email}} | {{.Phone}} | {{.Website}}
{{.Summary}}
{{range .Experiences}}
{{.DutiesSummary}}
{{range .Bullets}}* {{.Text}}
{{end}}{{end}}`,
		TextTemplate: `{{.FullName}}
{{.Email}} | {{.Phone}} | {{.Website}}
{{.Summary}}
{{range .Experiences}}
{{.DutiesSummary}}
{{range .Bullets}}- {{.Text}}
{{end}}{{end}}`,
	}

	realProf := &core.Profile{
		FullName: "Eleanor Vance",
		Email:    "eleanor.vance@hillhouse.org",
		Phone:    "+1-555-432-1098",
		Headline: "Principal Distributed Architect",
		Summary:  "Eleanor Vance is a distributed systems specialist.",
		Profiles: []core.SocialLink{
			{Network: "Website", URL: "https://eleanorvance.org"},
			{Network: "LinkedIn", Username: "eleanorvance", URL: "https://linkedin.com/in/eleanorvance"},
		},
	}

	// Tailored content generated by LLM pipeline (already deobfuscated at the LLM boundary)
	tailoredContent := &core.TailoredContent{
		Summary: "Seasoned engineer Eleanor Vance with expertise in fault tolerance. Contact: eleanor.vance@hillhouse.org or +1-555-432-1098. Portfolio: https://eleanorvance.org.",
		Experiences: []core.TailoredExperience{
			{
				SourceEntityID: "exp-1",
				Company:        "Acme",
				RoleTitle:      "Lead Architect",
				DutiesSummary:  "Eleanor Vance oversaw platform reliability.",
				Bullets: []core.TailoredBullet{
					{Text: "Eleanor Vance redesigned consensus replication for 99.999% uptime."},
				},
			},
		},
	}

	origSummary := tailoredContent.Summary

	rnd := renderer.New()
	output, err := rnd.Render(context.Background(), tmpl, realProf, tailoredContent)
	if err != nil {
		t.Fatalf("unexpected render error: %v", err)
	}

	// Verify no in-place mutation side effect on tailoredContent
	if tailoredContent.Summary != origSummary {
		t.Errorf("expected tailoredContent.Summary not to be mutated in-place: got %q, want %q", tailoredContent.Summary, origSummary)
	}

	assertAuthentic := func(t *testing.T, format string, content string) {
		t.Helper()

		// Must contain authentic values bound from core.Profile and core.TailoredContent
		if !strings.Contains(content, "Eleanor Vance") {
			t.Errorf("%s missing authentic FullName 'Eleanor Vance'", format)
		}
		if !strings.Contains(content, "eleanor.vance@hillhouse.org") {
			t.Errorf("%s missing authentic Email 'eleanor.vance@hillhouse.org'", format)
		}
		if !strings.Contains(content, "555-432-1098") {
			t.Errorf("%s missing authentic Phone digits '555-432-1098'", format)
		}
		if !strings.Contains(content, "https://eleanorvance.org") {
			t.Errorf("%s missing authentic Website 'https://eleanorvance.org'", format)
		}
	}

	assertAuthentic(t, "HTML", output.HTML)
	assertAuthentic(t, "Markdown", output.Markdown)
	assertAuthentic(t, "PlainText", output.PlainText)
}
